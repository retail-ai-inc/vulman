package scanner

import (
	"context"
	"encoding/json"
	"errors"
	"io"
	"os"
	"regexp"
	"strings"

	"vulman/internal/apperror"
	"vulman/internal/model"
	"vulman/internal/osvdb"
	"vulman/internal/sources"
	"vulman/internal/workflow"
)

const ComposerLockLabel = "PHP lockfile (local OSV)"

// LocalOSV never sends package names or repository contents to a remote service.
type LocalOSV interface {
	Query(context.Context, string, string, string) (osvdb.QueryResult, error)
}

var composerPackageName = regexp.MustCompile(`^[a-z0-9][a-z0-9_.-]*/[a-z0-9][a-z0-9_.-]*$`)

type composerPackage struct {
	Name    string `json:"name"`
	Version string `json:"version"`
}

func composerLockPackages(dir string) (_ []composerPackage, resultErr error) {
	invalid := func() error {
		return apperror.New("composer_lock_invalid", "The Composer lockfile is invalid or exceeds scanning limits. Provide a valid composer.lock generated by the project.")
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return nil, err
	}
	defer func() {
		if err := root.Close(); err != nil {
			resultErr = errors.Join(resultErr, err)
		}
	}()
	info, err := root.Lstat("composer.lock")
	if err != nil || !info.Mode().IsRegular() || info.Size() > 32<<20 {
		return nil, invalid()
	}
	f, err := root.Open("composer.lock")
	if err != nil {
		return nil, err
	}
	data, readErr := io.ReadAll(io.LimitReader(f, (32<<20)+1))
	if err := errors.Join(readErr, f.Close()); err != nil {
		return nil, err
	}
	var document struct {
		Packages json.RawMessage `json:"packages"`
		Dev      json.RawMessage `json:"packages-dev"`
	}
	if len(data) > 32<<20 || json.Unmarshal(data, &document) != nil || len(document.Packages) == 0 || document.Packages[0] != '[' {
		return nil, invalid()
	}
	var packages []composerPackage
	if json.Unmarshal(document.Packages, &packages) != nil {
		return nil, invalid()
	}
	if len(document.Dev) > 0 {
		var dev []composerPackage
		if document.Dev[0] != '[' || json.Unmarshal(document.Dev, &dev) != nil {
			return nil, invalid()
		}
		packages = append(packages, dev...)
	}
	if len(packages) > 10000 {
		return nil, invalid()
	}
	for i := range packages {
		p := &packages[i]
		p.Name = strings.ToLower(p.Name)
		if len(p.Name) > 200 || !composerPackageName.MatchString(p.Name) || p.Version == "" || len(p.Version) > 200 || strings.TrimSpace(p.Version) != p.Version {
			return nil, invalid()
		}
	}
	return packages, nil
}

func scanComposerLock(ctx context.Context, dir string, catalogue LocalOSV) ([]model.Finding, error) {
	if catalogue == nil {
		return nil, composerCatalogueRequired()
	}
	packages, err := composerLockPackages(dir)
	if err != nil {
		return nil, err
	}
	// Check readiness even for an empty dependency list.
	if _, err := catalogue.Query(ctx, "Packagist", "", ""); err != nil {
		if errors.Is(err, osvdb.ErrNotReady) {
			return nil, composerCatalogueRequired()
		}
		return nil, err
	}
	items, seen := []model.Finding{}, map[composerPackage]bool{}
	uncertain := false
	for _, pkg := range packages {
		if err := workflow.Wait(ctx); err != nil {
			return items, err
		}
		if seen[pkg] {
			continue
		}
		seen[pkg] = true
		result, err := catalogue.Query(ctx, "Packagist", pkg.Name, pkg.Version)
		if err != nil {
			return items, err
		}
		uncertain = uncertain || result.Uncertain
		for _, record := range result.Records {
			matched, unknown := osvdb.Match(record, "Packagist", pkg.Name, pkg.Version)
			uncertain = uncertain || unknown
			if !matched {
				continue
			}
			item := sources.OSVFinding(record, model.Asset{Name: pkg.Name, Version: pkg.Version, Ecosystem: "Packagist"})
			item.Sources, item.Match = []string{ComposerLockLabel}, "scanner"
			items = append(items, item)
		}
	}
	if uncertain {
		return items, apperror.New("composer_lock_uncertain", "Some Composer versions or advisory ranges could not be evaluated locally. Confirmed findings are shown, previous findings are retained, and the scan is incomplete. Use composer audit for additional coverage.")
	}
	return items, nil
}

func composerCatalogueRequired() error {
	return apperror.New("composer_packagist_required", "Download the Packagist ecosystem under Configuration → Local OSV database before scanning PHP lockfiles. The standalone scanner also requires --data-dir pointing to that workspace.")
}
